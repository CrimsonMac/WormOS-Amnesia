/*
 * Boot menu entries for recent snapshots.
 *
 * The GRUB configuration on the EFI partition sources @snapshots/grub.cfg,
 * which snap rewrites whenever the list of snapshots changes. Each entry
 * boots the kernel and initramfs saved in that snapshot and asks the
 * initramfs to rewind to it (wormos.rewind=ID), so a rewind can be chosen
 * before any program from the installed system has started.
 *
 * First comes safe mode: the newest system snapshot not marked suspect,
 * booted with wormos.safe (no network). Without one, the current system.
 */

#define _GNU_SOURCE
#include <errno.h>
#include <limits.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#include <unistd.h>

#include "snap.h"

#define MENU_FILE     "grub.cfg"
#define MENU_ENTRIES  10

/* GRUB single-quoted strings cannot contain a quote. */
static void menu_text(const char *in, char *out, size_t len)
{
	size_t n = 0;

	for (; *in && n + 1 < len; in++)
		out[n++] = (*in == '\'' || (unsigned char)*in < ' ') ? '"' : *in;
	out[n] = '\0';
}

void menu_update(void)
{
	char path[PATH_MAX], tmp[PATH_MAX + 8], store[PATH_MAX];
	struct snapshot *list;
	int n, shown = 0;
	FILE *f;

	path_join(store, sizeof(store), top, SUBVOL_STORE);
	path_join(path, sizeof(path), store, MENU_FILE);
	snprintf(tmp, sizeof(tmp), "%s.tmp", path);
	f = fopen(tmp, "we");
	if (!f) {
		warn("cannot update the boot menu: %s", strerror(errno));
		return;
	}

	n = store_list(&list);
	fprintf(f, "# Snapshot entries, generated by snap.\n");
	for (int i = n - 1; i >= -1; i--) {
		if (i < 0) {
			fprintf(f, "menuentry 'Safe mode (no network)' --unrestricted {\n"
				"\tlinux /@/boot/vmlinuz $wormos_cmdline wormos.safe\n"
				"\tinitrd /@/boot/initramfs.img\n"
				"}\n");
			break;
		}
		if (!(list[i].scope & SCOPE_SYSTEM) || list[i].suspect)
			continue;
		fprintf(f,
			"menuentry 'Safe mode (snapshot %d, no network)' --unrestricted {\n"
			"\tlinux /%s/%d/%s/boot/vmlinuz $wormos_cmdline wormos.rewind=%d wormos.safe\n"
			"\tinitrd /%s/%d/%s/boot/initramfs.img\n"
			"}\n",
			list[i].id, SUBVOL_STORE, list[i].id, SNAP_SYSTEM, list[i].id,
			SUBVOL_STORE, list[i].id, SNAP_SYSTEM);
		break;
	}
	for (int i = n - 1; i >= 0 && shown < MENU_ENTRIES; i--) {
		const struct snapshot *s = &list[i];
		char date[32], comment[COMMENT_MAX];
		struct tm tm;

		if (!(s->scope & SCOPE_SYSTEM))
			continue;
		if (shown++ == 0)
			fprintf(f, "submenu 'Rewind to a snapshot' --unrestricted {\n");
		localtime_r(&s->date, &tm);
		strftime(date, sizeof(date), "%Y-%m-%d %H:%M", &tm);
		menu_text(s->comment, comment, sizeof(comment));
		fprintf(f,
			"\tmenuentry 'Snapshot %d   %s   %s' --unrestricted {\n"
			"\t\tlinux /%s/%d/%s/boot/vmlinuz $wormos_cmdline wormos.rewind=%d\n"
			"\t\tinitrd /%s/%d/%s/boot/initramfs.img\n"
			"\t}\n",
			s->id, date, comment,
			SUBVOL_STORE, s->id, SNAP_SYSTEM, s->id,
			SUBVOL_STORE, s->id, SNAP_SYSTEM);
	}
	if (shown)
		fprintf(f, "}\n");
	free(list);

	if (fclose(f) != 0 || rename(tmp, path) < 0) {
		warn("cannot update the boot menu: %s", strerror(errno));
		unlink(tmp);
	}
	status_update();
}
